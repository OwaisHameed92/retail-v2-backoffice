/** DirectDebitData::for: the Direct Debit part of the tenant Billing tab (module 1.12). */
export interface DirectDebitData {
    enabled: boolean;
    environment: 'sandbox' | 'live' | 'none';
    mode: BillingMode;
    setupFee: {
        /** Decimal strings (net). */
        plan: string;
        override: string | null;
        net: string;
        gross: string;
        hasFee: boolean;
        method: SetupFeeMethod;
        instalments: number;
        invoicedAt: string | null;
        /** VAT rate on this business's invoices ("20.00"), null without VAT. */
        vatRate: string | null;
        /** P11: the plan charges the setup fee for each till. */
        perTill: boolean;
        /** P11: the plan's setup fee per till (net) and this business's own, for tills added later. */
        tillFeePlan: string;
        tillFeeOverride: string | null;
        /** P11: tills now, tills a setup fee covers (null = not tracked: all of them), tills waiting for their fee. */
        tills: number;
        coveredTills: number | null;
        heldTills: number;
    };
    mandate: {
        id: string | null;
        status: string | null;
        statusLabel: string;
        usable: boolean;
        lostAt: string | null;
        activeAt: string | null;
        setupSentAt: string | null;
    };
    subscription: {
        id: string | null;
        status: string | null;
        statusLabel: string;
        live: boolean;
        amount: string | null;
        cycle: BillingCycle | null;
        nextChargeDate: string | null;
        expected: string;
        expectedTills: number;
        /** "2 tills" / "1 branch" (module 1.13). */
        expectedUnits: string;
        inStep: boolean;
        reconciledAt: string | null;
    };
    payments: { data: DirectDebitPaymentRow[]; total: number };
    options: { modes: Option<BillingMode>[]; setupFeeMethods: Option<SetupFeeMethod>[]; maxInstalments: number };
    graceDays: number;
    /** Pakistan plan P5: only where fees are paid by hand. */
    manual?: { methods: Option<PaymentMethod>[]; methodsText: string; dueDays: number };
    /** Module 1.13: pricing mode and prices (plan and this company's override). */
    pricing: {
        mode: PricingMode;
        modeLabel: string;
        unit: string;
        unitPrice: string | null;
        unitsLabel: string;
        plan: { name: string; mode: PricingMode; modeLabel: string; monthly: string; yearly: string } | null;
        override: { mode: PricingMode | null; monthly: string | null; yearly: string | null };
        overridden: boolean;
        recurring: string;
        recurringIsZero: boolean;
        per: string;
        options: Option<PricingMode>[];
    };
    /** Owner rules 2026-10-05: setup only, setup + recurring, or recurring only. */
    planType: { value: PlanBillingType; label: string } | null;
    /** The setup fee (upfront): one thing, always paid by hand (cash, card or bank transfer). */
    upfront: {
        recorded: boolean;
        amount: string | null;
        method: string | null;
        recordedAt: string | null;
        canRecord: boolean;
        status: SetupFeeStatus;
        statusLabel: string;
        /** Formatted, VAT included. */
        total: string;
        owed: string;
        invoiced: boolean;
        nextDue: string | null;
        methods: Option<string>[];
    };
    /** Waiting for the customer's first mandate: the deadline (null when none is needed). */
    deadline: MandateDeadline | null;
}

