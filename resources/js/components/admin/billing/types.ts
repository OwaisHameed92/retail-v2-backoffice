import { type Paginated } from '@/components/shared/data-table';

export type InvoiceStatus = 'draft' | 'issued' | 'partiallyPaid' | 'paid' | 'overdue' | 'void';

export type PaymentMethod = 'cash' | 'bankTransfer' | 'other' | 'online';

export type BillingCycle = 'monthly' | 'yearly';

export interface Option<T extends string = string> {
    value: T;
    label: string;
}

export interface CompanyRef {
    id: string;
    name: string;
}

/** InvoiceData::row. Money is formatted ("£1,234.50"); dates are calendar dates "YYYY-MM-DD". */
export interface InvoiceRow {
    id: string;
    number: string | null;
    displayNumber: string;
    status: InvoiceStatus;
    statusLabel: string;
    company: CompanyRef;
    period: string;
    periodStart: string;
    periodEnd: string;
    issueDate: string | null;
    dueDate: string | null;
    total: string;
    balance: string;
    /** Decimal string, e.g. "90.00". */
    balanceRaw: string;
    isOpen: boolean;
    daysOverdue: number;
    autoGenerated: boolean;
}

/** InvoiceDocument::for: everything printed on the invoice, formatted. */
export interface InvoiceDocumentData {
    type: 'invoice';
    number: string | null;
    title: string;
    status: InvoiceStatus;
    statusLabel: string;
    issueDate: string | null;
    dueDate: string | null;
    period: string;
    cycle: string;
    seller: {
        name: string;
        legalName: string;
        address: string[];
        companyNumber: string | null;
        vatNumber: string | null;
        email: string | null;
        phone: string | null;
    };
    billTo: { name: string; address: string[]; emails: string[]; companyNumber: string | null; vatNumber: string | null };
    hasVat: boolean;
    vatRate: string;
    lines: { id: string; description: string; quantity: string; unitPrice: string; net: string; vat: string; gross: string }[];
    subtotal: string;
    vatTotal: string;
    total: string;
    amountPaid: string;
    amountCredited: string;
    balance: string;
    hasPayments: boolean;
    hasCredits: boolean;
    payments: { number: string | null; date: string | null; method: string | null; amount: string }[];
    creditNotes: { number: string; date: string; reason: string; total: string }[];
    notes: string | null;
    paidOn: string | null;
    voidedOn: string | null;
    voidReason: string | null;
    bank: string[];
    reference: string | null;
}

export interface ActivityRow {
    id: string;
    action: string;
    description: string;
    actorKind: 'admin' | 'user' | 'system' | 'other';
    actorName: string;
    createdAt: string | null;
}

/** InvoiceData::detail. */
export interface InvoiceDetail extends InvoiceRow {
    document: InvoiceDocumentData;
    vatRate: string;
    notes: string | null;
    cycle: BillingCycle;
    prorated: boolean;
    companyStatus: string | null;
    amountPaid: string;
    amountCredited: string;
    issuedAt: string | null;
    paidAt: string | null;
    voidedAt: string | null;
    voidReason: string | null;
    lastSentAt: string | null;
    sentCount: number;
    recipients: string[];
    lines: { id: string; description: string; quantity: string; unitPrice: string; hasLicence: boolean; licenceId: string | null }[];
    payments: { id: string; paymentId: string; number: string | null; method: string | null; receivedAt: string | null; amount: string; released: boolean }[];
    replaces: { id: string; number: string | null } | null;
    replacedBy: { id: string; number: string } | null;
    can: { manage: boolean; edit: boolean; issue: boolean; delete: boolean; send: boolean; recordPayment: boolean; credit: boolean; void: boolean };
    maxCredit: string;
    hasPayments: boolean;
}

/** PaymentData::row. */
export interface PaymentRow {
    id: string;
    number: string;
    company: CompanyRef;
    method: PaymentMethod;
    methodLabel: string;
    amount: string;
    unallocated: string;
    hasCredit: boolean;
    receivedAt: string;
    reference: string | null;
    receivedBy: string | null;
    invoices: { id: string; number: string | null }[];
}

export interface PaymentDetail extends PaymentRow {
    notes: string | null;
    gateway: string | null;
    gatewayReference: string | null;
    allocations: {
        id: string;
        invoiceId: string;
        invoiceNumber: string | null;
        invoiceStatus: InvoiceStatus | null;
        amount: string;
        released: boolean;
        releasedAt: string | null;
        createdAt: string | null;
    }[];
}

/** TenantBilling::openInvoices. `balance` is a decimal string. */
export interface OpenInvoice {
    id: string;
    number: string | null;
    balance: string;
    balanceLabel: string;
    dueDate: string | null;
    status: InvoiceStatus;
    period: string;
}

/** TenantBilling::for (the tenant page's Billing tab). */
export interface TenantBillingData {
    settings: {
        billingName: string | null;
        billingAddress: string | null;
        emails: string[];
        cycle: BillingCycle;
        paymentTermsDays: number;
        vatApplies: boolean;
        effectiveName: string;
        effectiveAddress: string | null;
        recipients: string[];
        recipientsAreOwners: boolean;
    };
    summary: {
        balance: string;
        hasBalance: boolean;
        openCount: number;
        overdue: string;
        overdueCount: number;
        credit: string;
        creditRaw: string;
        hasCredit: boolean;
        lastPayment: { amount: string; receivedAt: string; method: string } | null;
        nextPeriod: { start: string; end: string; label: string };
        suspendedForBilling: boolean;
    };
    invoices: { data: InvoiceRow[]; total: number };
    payments: { data: PaymentRow[]; total: number };
    openInvoices: OpenInvoice[];
    options: { cycles: Option<BillingCycle>[]; methods: Option<PaymentMethod>[] };
    vatEnabled: boolean;
    vatRate: string;
    canManage: boolean;
}

