import { dueLabel, formatDay } from '@/components/admin/billing/format';
import { InvoiceStatusBadge } from '@/components/admin/billing/invoice-status-badge';
import { type InvoiceRow } from '@/components/admin/billing/types';
import { cn } from '@/lib/utils';
import { type ColumnDef } from '@tanstack/react-table';
import { Sparkles } from 'lucide-react';

/** "INV-000123" in mono, or a muted "Draft". */
export function InvoiceNumber({ row }: { row: Pick<InvoiceRow, 'number' | 'autoGenerated' | 'status'> }) {
    if (!row.number) {
        return (
            <span className="text-muted-foreground inline-flex items-center gap-1.5 font-medium">
                Draft
                {row.autoGenerated && <Sparkles className="size-3.5" aria-label="Created by the billing run" />}
            </span>
        );
    }

    return <span className={cn('font-mono text-[13px] font-medium whitespace-nowrap', row.status === 'void' && 'text-muted-foreground line-through')}>{row.number}</span>;
}

/** Due date with "3 days overdue" in red or "Due in 2 days" in amber. */
export function DueDate({ row }: { row: Pick<InvoiceRow, 'dueDate' | 'isOpen' | 'status'> }) {
    if (!row.dueDate) {
        return <span className="text-muted-foreground">Not issued</span>;
    }
    const label = dueLabel(row.dueDate, row.isOpen);
    const overdue = row.isOpen && (row.status === 'overdue' || (label?.endsWith('overdue') ?? false));
    const soon = row.isOpen && !overdue && label !== null && /Due (today|tomorrow|in [1-6] days)/.test(label);

    return (
        <div className="leading-tight whitespace-nowrap">
            <div className={cn('tabular-nums', overdue && 'text-destructive font-medium')}>{formatDay(row.dueDate)}</div>
            {label && <div className={cn('text-xs', overdue ? 'text-destructive' : soon ? 'text-warning-foreground' : 'text-muted-foreground')}>{label}</div>}
        </div>
    );
}

export function Money({ value, muted = false, strong = false }: { value: string; muted?: boolean; strong?: boolean }) {
    return <span className={cn('whitespace-nowrap tabular-nums', muted && 'text-muted-foreground', strong && 'font-semibold')}>{value}</span>;
}

/**
 * Columns of the admin invoice list for a breakpoint (see useBreakpoint). Sortable ids match InvoiceQuery::SORTABLE.
 */
export function invoiceColumns({ showBusiness = true, breakpoint = 4 }: { showBusiness?: boolean; breakpoint?: number } = {}): ColumnDef<InvoiceRow>[] {
    const columns: ColumnDef<InvoiceRow>[] = [
        {
            id: 'sequence',
            header: 'Invoice',
            enableSorting: true,
            meta: { mobile: 'title' },
            cell: ({ row }) => (
                <div className="min-w-0 leading-tight">
                    <InvoiceNumber row={row.original} />
                    <div className="text-muted-foreground mt-0.5 truncate text-xs">
                        {showBusiness && breakpoint < 2 ? `${row.original.company.name} · ` : ''}
                        {row.original.period}
                    </div>
                </div>
            ),
        },
    ];

    if (showBusiness && breakpoint >= 2) {
        columns.push({
            id: 'company_name',
            header: 'Business',
            enableSorting: true,
            cell: ({ row }) => <span className="block max-w-56 truncate font-medium">{row.original.company.name}</span>,
        });
    }

    if (breakpoint >= 3) {
        columns.push({
            id: 'period_start',
            header: 'Period',
            enableSorting: true,
            cell: ({ row }) => <span className="whitespace-nowrap">{row.original.period}</span>,
        });
    }

    columns.push(
        {
            id: 'total',
            header: 'Total',
            enableSorting: true,
            meta: { align: 'right' },
            cell: ({ row }) => <Money value={row.original.total} />,
        },
        {
            id: 'balance',
            header: 'Balance',
            enableSorting: true,
            meta: { align: 'right' },
            cell: ({ row }) => <Money value={row.original.isOpen ? row.original.balance : '—'} muted={!row.original.isOpen} strong={row.original.isOpen} />,
        },
        {
            id: 'status',
            header: 'Status',
            cell: ({ row }) => <InvoiceStatusBadge status={row.original.status} />,
        },
        {
            id: 'due_date',
            header: 'Due',
            enableSorting: true,
            cell: ({ row }) => <DueDate row={row.original} />,
        },
    );

    return columns;
}
