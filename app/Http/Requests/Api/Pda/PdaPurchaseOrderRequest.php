<?php

namespace App\Http\Requests\Api\Pda;

use Illuminate\Foundation\Http\FormRequest;

/**
 * `POST /api/pda/purchase-orders` and `PUT …/{id}` (legacy body): supplier, expected delivery date, notes, status
 * (draft | sent) and `items` (replace the lines); on create an optional `client_reference` (a UUID, idempotency). Quantities
 * are whole units of the line's unit, or up to 3 decimals for a weighed (kg) product (the action checks which); costs
 * up to 4 decimal places, as the portal's head-office order form. Ids are checked against the business by the action.
 */
class PdaPurchaseOrderRequest extends FormRequest
{
    private const COST = 'regex:/^\d{1,7}(\.\d{1,4})?$/';

    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            ...($this->isMethod('post') ? ['client_reference' => ['nullable', 'string', 'uuid']] : []),
            'supplier_id' => ['required', 'string', 'max:64'],
            'expected_delivery_date' => ['nullable', 'date_format:Y-m-d'],
            'notes' => ['nullable', 'string', 'max:1000'],
            'status' => ['nullable', 'in:draft,sent'],
            'items' => ['required', 'array', 'min:1', 'max:500'],
            'items.*.product_id' => ['required', 'string', 'max:64', 'distinct'],
            'items.*.quantity_ordered' => ['required', 'numeric', 'gt:0', 'max:100000', 'decimal:0,3'],
            'items.*.unit_cost' => ['nullable', self::COST],
            'items.*.conversion_factor' => ['nullable', 'integer', 'min:1', 'max:10000'],
            'items.*.base_unit_cost' => ['nullable', self::COST],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'items.required' => 'Add at least one product.',
            'items.min' => 'Add at least one product.',
            'items.*.product_id.distinct' => 'Each product may be on the order once.',
            'items.*.quantity_ordered.numeric' => 'Enter the quantity as a number.',
            'items.*.quantity_ordered.gt' => 'Order at least one unit.',
            'items.*.quantity_ordered.decimal' => 'Enter up to 3 decimal places (weighed products only).',
            'client_reference.uuid' => 'client_reference must be a UUID generated by the app.',
            'items.*.unit_cost.regex' => 'Enter the cost with up to 4 decimal places.',
            'items.*.base_unit_cost.regex' => 'Enter the cost with up to 4 decimal places.',
        ];
    }

    /**
     * @return array<string, mixed>
     */
    public function order(): array
    {
        return $this->safe()->except('client_reference');
    }

    /** The app's idempotency UUID (create only), lower case; null when not sent. */
    public function clientReference(): ?string
    {
        $value = $this->isMethod('post') ? $this->validated('client_reference') : null;

        return is_string($value) && $value !== '' ? mb_strtolower($value) : null;
    }
}
