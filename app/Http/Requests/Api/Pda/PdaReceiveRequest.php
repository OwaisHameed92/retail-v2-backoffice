<?php

namespace App\Http\Requests\Api\Pda;

use App\Http\Requests\Api\Pda\Concerns\PdaClientReference;
use Illuminate\Foundation\Http\FormRequest;

/**
 * `POST /api/pda/purchase-orders/{id}/receive` (PDA_PHASE2_REQUEST §3): the delivery note number, when it arrived,
 * a note and the items (each an order line by `purchase_order_item_id`, or `product_id`, with the quantity in THIS
 * delivery in base units, > 0, 4 dp). No `items` = everything still outstanding. `client_reference` as the other
 * stock calls.
 */
class PdaReceiveRequest extends FormRequest
{
    use PdaClientReference;

    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            ...$this->clientReferenceRules(),
            'reference_no' => ['nullable', 'string', 'max:60'],
            'received_at' => ['nullable', 'date'],
            'note' => ['nullable', 'string', 'max:500'],
            'items' => ['nullable', 'array', 'min:1', 'max:500'],
            'items.*.purchase_order_item_id' => ['nullable', 'required_without:items.*.product_id', 'string', 'max:64'],
            'items.*.product_id' => ['nullable', 'string', 'max:64'],
            'items.*.quantity_received' => ['required', 'numeric', 'gt:0', 'max:1000000', 'decimal:0,4'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'items.*.purchase_order_item_id.required_without' => 'Name the order line (purchase_order_item_id).',
            'items.*.quantity_received.gt' => 'Enter the quantity that arrived (above 0).',
            'items.*.quantity_received.decimal' => 'Enter the quantity in base units with up to 4 decimal places.',
            'client_reference.uuid' => 'client_reference must be a UUID generated by the app.',
        ];
    }
}
