<?php

namespace App\Http\Requests\Api\Pda;

use App\Http\Requests\Api\Pda\Concerns\PdaClientReference;
use Illuminate\Foundation\Http\FormRequest;

/**
 * `POST /api/pda/stock-adjustments` and `PUT …/{id}` (PDA_PHASE2_REQUEST §1): product, type, base-unit quantity (4 dp),
 * cost (4 dp), reason (≤ 255), the entered unit (display only) and, on create, `client_reference`. The action
 * checks the rules that depend on the type and the product.
 */
class PdaStockAdjustmentRequest extends FormRequest
{
    use PdaClientReference;

    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            ...$this->clientReferenceRules(),
            'product_id' => ['required', 'string', 'max:64'],
            'adjustment_type' => ['required', 'string', 'in:stockIncrease,stockDecrease,openingStock,stockCount'],
            'quantity' => ['required', 'numeric', 'min:0', 'max:1000000', 'decimal:0,4'],
            'unit_cost' => ['nullable', 'numeric', 'min:0', 'max:99999999', 'decimal:0,4'],
            'reason' => ['nullable', 'string', 'max:255'],
            'product_unit_id' => ['nullable', 'string', 'max:64'],
            'entered_quantity' => ['nullable', 'numeric', 'min:0', 'max:1000000', 'decimal:0,4'],
            'conversion_to_base' => ['nullable', 'numeric', 'gt:0', 'max:100000', 'decimal:0,4'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'adjustment_type.in' => 'adjustment_type is stockIncrease, stockDecrease, openingStock or stockCount.',
            'quantity.decimal' => 'Enter the quantity in base units with up to 4 decimal places.',
            'unit_cost.decimal' => 'Enter the cost with up to 4 decimal places.',
            'client_reference.uuid' => 'client_reference must be a UUID generated by the app.',
        ];
    }
}
