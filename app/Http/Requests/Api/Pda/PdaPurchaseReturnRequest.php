<?php

namespace App\Http\Requests\Api\Pda;

use App\Http\Requests\Api\Pda\Concerns\PdaClientReference;
use Illuminate\Foundation\Http\FormRequest;

/**
 * `POST /api/pda/purchase-returns` and `PUT …/{id}` (PDA_PHASE2_REQUEST §4): supplier, optional order and reference,
 * a reason, and up to 500 items (product, optional order line, quantity in base units > 0, cost per base unit, a
 * reason); on create `client_reference`.
 */
class PdaPurchaseReturnRequest extends FormRequest
{
    use PdaClientReference;

    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            ...$this->clientReferenceRules(),
            'supplier_id' => ['required', 'string', 'max:64'],
            'purchase_order_id' => ['nullable', 'string', 'max:64'],
            'reference_no' => ['nullable', 'string', 'max:60'],
            'return_reason' => ['nullable', 'string', 'max:255'],
            'items' => ['required', 'array', 'min:1', 'max:500'],
            'items.*.product_id' => ['required', 'string', 'max:64'],
            'items.*.purchase_order_item_id' => ['nullable', 'string', 'max:64'],
            'items.*.quantity' => ['required', 'numeric', 'gt:0', 'max:1000000', 'decimal:0,4'],
            'items.*.cost_price' => ['nullable', 'numeric', 'min:0', 'max:99999999', 'decimal:0,4'],
            'items.*.reason' => ['nullable', 'string', 'max:255'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'items.required' => 'Add at least one product to return.',
            'items.min' => 'Add at least one product to return.',
            'items.*.quantity.gt' => 'Return at least some of the product (above 0).',
            'items.*.quantity.decimal' => 'Enter the quantity in base units with up to 4 decimal places.',
            'items.*.cost_price.decimal' => 'Enter the cost with up to 4 decimal places.',
            'client_reference.uuid' => 'client_reference must be a UUID generated by the app.',
        ];
    }
}
