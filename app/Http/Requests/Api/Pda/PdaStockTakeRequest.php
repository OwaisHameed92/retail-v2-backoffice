<?php

namespace App\Http\Requests\Api\Pda;

use App\Http\Requests\Api\Pda\Concerns\PdaClientReference;
use Illuminate\Foundation\Http\FormRequest;

/**
 * `POST /api/pda/stock-takes` and `PUT …/{id}` (PDA_PHASE2_REQUEST §1a): a name, a note and up to 500 lines, each a
 * product (once) with the counted quantity in base units (0 allowed, 4 dp); on create `client_reference`.
 */
class PdaStockTakeRequest extends FormRequest
{
    use PdaClientReference;

    public function authorize(): bool
    {
        return true;
    }

    /**
     * @return array<string, mixed>
     */
    public function rules(): array
    {
        return [
            ...$this->clientReferenceRules(),
            'name' => ['required', 'string', 'max:120'],
            'note' => ['nullable', 'string', 'max:500'],
            'lines' => ['required', 'array', 'min:1', 'max:500'],
            'lines.*.product_id' => ['required', 'string', 'max:64', 'distinct'],
            'lines.*.counted_quantity' => ['required', 'numeric', 'min:0', 'max:1000000', 'decimal:0,4'],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'lines.required' => 'Count at least one product.',
            'lines.min' => 'Count at least one product.',
            'lines.*.product_id.distinct' => 'Each product may be in the stock take once.',
            'lines.*.counted_quantity.decimal' => 'Enter the counted quantity in base units with up to 4 decimal places.',
            'client_reference.uuid' => 'client_reference must be a UUID generated by the app.',
        ];
    }
}
